"""Turn one natural-language request into a function call.

The JSON is built piece by piece: the structure is forced by the program
(no model call), the function name and each value are generated by the
model under a constraint. The result is valid by construction, then
checked again by json.loads and pydantic (architecture D5).
"""

import json
from typing import Any

from pydantic import BaseModel, ConfigDict

from src.decoding.constraints import ChoiceConstraint, make_constraint
from src.decoding.decoder import decode_value
from src.llm.engine import Engine
from src.models import FunctionCall, FunctionDefinition
from src.prompting import build_prompt

MAX_NAME_TOKENS = 20
MAX_VALUE_TOKENS = 30


def _convert(values: dict[str, Any], fn: FunctionDefinition) -> dict[str, Any]:
    """Give each value its declared Python type ("number" -> float).

    json.loads reads 2 as an int; the output expects 2.0 for a number.
    Other types already come out right.
    """
    return {
        name: float(values[name]) if spec.type == "number" else values[name]
        for name, spec in fn.parameters.items()
    }


class FunctionCaller(BaseModel):
    """Generate function calls with the model and the definitions.

    Attributes:
        engine: the model (not a pydantic type, hence
            arbitrary_types_allowed).
        functions: the available functions, in file order.
    """

    model_config = ConfigDict(arbitrary_types_allowed=True)

    engine: Engine
    functions: list[FunctionDefinition]

    def _force(self, ids: list[int], text: str,
               segment: str) -> tuple[list[int], str]:
        """Append fixed text to both the ids and the JSON, without the model.

        Returns new lists: the caller's `ids` is not modified.
        """
        return ids + self.engine.encode(segment), text + segment

    def _choose_function(
        self, ids: list[int], text: str
    ) -> tuple[list[int], str, FunctionDefinition]:
        """Let the model pick the function name among the defined ones.

        Returns:
            The extended ids and JSON, and the chosen definition.
        """
        names = [fn.name for fn in self.functions]
        constraint = ChoiceConstraint(options=names)
        ids, generated = decode_value(self.engine, ids, constraint,
                                      MAX_NAME_TOKENS)
        if not constraint.is_complete():
            closing = constraint.closing()
            ids, generated = self._force(ids, generated, closing)
        name = generated[:-1]
        fn = next(f for f in self.functions if f.name == name)
        return ids, text + generated, fn

    def _generate_parameters(
        self, ids: list[int], text: str, fn: FunctionDefinition
    ) -> tuple[list[int], str]:
        """Write `, "parameters": {...}` with one generated value per key.

        Keys are forced in definition order. Numbers and booleans end on
        "," or "}" themselves; a string ends on its quote, so the marker
        is forced after it. A value cut by the token limit is closed
        with `closing()`, so the JSON stays valid.
        """
        ids, text = self._force(ids, text, ', "parameters": {')
        if not fn.parameters:
            return self._force(ids, text, "}")
        last = len(fn.parameters) - 1
        for i, (name, spec) in enumerate(fn.parameters.items()):
            end = "}" if i == last else ","
            prefix = " " if i > 0 else ""
            key = f'{prefix}"{name}": '
            if spec.type == "string":
                key += '"'
            ids, text = self._force(ids, text, key)
            constraint = make_constraint(spec, end)
            ids, value = decode_value(self.engine, ids, constraint,
                                      MAX_VALUE_TOKENS)
            text += value
            if not constraint.is_complete():
                ids, text = self._force(ids, text, constraint.closing())
            if spec.type == "string":
                ids, text = self._force(ids, text, end)
        return ids, text

    def call(self, prompt: str) -> FunctionCall:
        """Build the function call for one request.

        Args:
            prompt: the request, copied unchanged into the result.

        Returns:
            The call, with values in their declared types.

        Raises:
            DecodingError: a constraint got stuck (a bug).
        """
        ids = self.engine.encode(build_prompt(self.functions, prompt))
        text = ""
        ids, text = self._force(ids, text, '{"name": "')
        ids, text, fn = self._choose_function(ids, text)
        ids, text = self._generate_parameters(ids, text, fn)
        ids, text = self._force(ids, text, "}")
        data = json.loads(text)
        return FunctionCall(
            prompt=prompt,
            name=data["name"],
            parameters=_convert(data["parameters"], fn),
        )
